# ---------------------------------------------------------------------------
# Binary helpers
# ---------------------------------------------------------------------------

def u32(value: int) -> bytes:
    """Little-endian unsigned 32-bit integer."""
    return struct.pack("<I", value)


def i32(value: int) -> bytes:
    """Little-endian signed 32-bit integer."""
    return struct.pack("<i", value)


def u8(value: int) -> bytes:
    """Single byte."""
    return bytes([value & 0xFF])


def fname(index: int = 0, number: int = 0) -> bytes:
    """FName: index (u32) + number (u32)."""
    return u32(index) + u32(number)


def empty_ftext() -> bytes:
    """Minimal FText (None history, no culture-invariant string)."""
    return u32(0) + u8(0xFF) + u32(0)  # flags + history_type(-1) + bHasCulture=false


def empty_fstring() -> bytes:
    """Minimal FString (length=0)."""
    return i32(0)


def simple_pin_type() -> bytes:
    """Minimal FEdGraphPinType."""
    data = b""
    data += fname(0, 0)       # PinCategory
    data += fname(0, 0)       # PinSubCategory
    data += i32(0)            # PinSubCategoryObject (PackageIndex)
    data += u8(0)             # ContainerType
    data += u32(0)            # bIsReference
    data += u32(0)            # bIsWeakPointer
    # FSimpleMemberReference
    data += i32(0)            # MemberParent (PackageIndex)
    data += fname(0, 0)       # MemberName
    data += u32(0) * 4        # MemberGuid (16 bytes)
    data += u32(0)            # bIsConst
    data += u32(0)            # bIsUObjectWrapper
    data += u32(0)            # bSerializeAsSinglePrecisionFloat
    return data


def build_single_pin() -> bytes:
    """Build binary data for a single minimal UEdGraphPin record."""
    data = b""
    # --- Pin reference ---
    data += u32(0)             # bNullPtr = false
    data += i32(0)             # OwningNode (PackageIndex)
    data += u32(0) * 4         # PinId (FGuid)

    # --- Pin body ---
    data += i32(0)             # OwningNode (repeated)
    data += u32(0) * 4         # PinId (repeated)
    data += fname(0, 0)        # PinName
    data += empty_ftext()      # PinFriendlyName
    data += i32(-1)            # SourceIndex (INDEX_NONE)
    data += empty_fstring()    # PinToolTip
    data += u8(0)              # Direction
    data += simple_pin_type()  # PinType
    data += empty_fstring()    # DefaultValue
    data += empty_fstring()    # AutogeneratedDefaultValue
    data += i32(0)             # DefaultObject (PackageIndex)
    data += empty_ftext()      # DefaultTextValue
    data += i32(0)             # LinkedTo count = 0
    data += i32(0)             # SubPins count = 0
    data += u32(1)             # ParentPin bNullPtr = true
    data += u32(1)             # RefPassThroughConnection bNullPtr = true
    # Editor-only tail
    data += u32(0) * 4         # PersistentGuid (FGuid)
    data += u32(0)             # BitField
    return data


def build_tail(guid_marker: int, pins: list[bytes]) -> bytes:
    """Build tail data: guid_marker + [optional 16-byte GUID] + pin_count + pin data."""
    data = b""
    data += u32(guid_marker)
    if guid_marker != 0:
        data += u32(0) * 4     # 16-byte GUID
    data += i32(len(pins))
    for pin in pins:
        data += pin
    return data


