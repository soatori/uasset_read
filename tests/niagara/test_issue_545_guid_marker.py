class TestGuidMarkerZero:
    """GUID marker = 0: no GUID bytes consumed."""

    def test_single_pin_decoded(self):
        """When guid_marker=0, single pin decodes correctly."""
        pin = build_single_pin()
        tail = build_tail(guid_marker=0, pins=[pin])

        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []
        mock_export = MockExport()

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail), export=mock_export)

        assert len(result) == 1
        # Empty name_map + tolerant mode returns "None" for out-of-range index
        assert result[0]["pin_name"] in ("", "None")

    def test_multiple_pins_decoded(self):
        """When guid_marker=0, multiple pins decode correctly."""
        pin = build_single_pin()
        tail = build_tail(guid_marker=0, pins=[pin, pin, pin])

        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []
        mock_export = MockExport()

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail), export=mock_export)

        assert len(result) == 3

    def test_zero_pins(self):
        """When guid_marker=0 and pin_count=0, returns empty list."""
        tail = build_tail(guid_marker=0, pins=[])

        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail))

        assert result == []


class TestGuidMarkerNonZero:
    """GUID marker != 0: 16-byte GUID must be consumed."""

    def test_single_pin_decoded_with_guid(self):
        """When guid_marker!=0, single pin decodes correctly after GUID consumption."""
        pin = build_single_pin()
        tail = build_tail(guid_marker=0xDEADBEEF, pins=[pin])

        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []
        mock_export = MockExport()

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail), export=mock_export)

        assert len(result) == 1

    def test_multiple_pins_decoded_with_guid(self):
        """When guid_marker!=0, multiple pins decode correctly after GUID consumption."""
        pin = build_single_pin()
        tail = build_tail(guid_marker=1, pins=[pin, pin])

        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []
        mock_export = MockExport()

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail), export=mock_export)

        assert len(result) == 2

    def test_pin_alignment_with_guid(self):
        """Pin data is correctly aligned after GUID consumption (pin_id is valid hex)."""
        pin = build_single_pin()
        tail = build_tail(guid_marker=0x12345678, pins=[pin])

        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []
        mock_export = MockExport()

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail), export=mock_export)

        assert len(result) == 1
        pin_id = result[0]["pin_id"]
        # pin_id should be a valid hex GUID format
        parts = pin_id.split("-")
        assert len(parts) == 4
        for part in parts:
            assert len(part) == 8
            int(part, 16)  # should not raise

    def test_direction_decoded_correctly_with_guid(self):
        """Pin direction is correctly decoded after GUID consumption."""
        pin = build_single_pin()
        tail = build_tail(guid_marker=0xABCD, pins=[pin])

        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []
        mock_export = MockExport()

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail), export=mock_export)

        assert len(result) == 1
        assert result[0]["direction"] == 0


class TestTailSizeEdgeCases:
    """Edge cases for tail size validation."""

    def test_tail_too_small_returns_empty(self):
        """Tail smaller than 8 bytes returns empty list."""
        tail = u32(0) + u8(0)  # Only 5 bytes (< 8 minimum)
        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail))

        assert result == []

    def test_tail_exactly_minimum_with_guid_marker(self):
        """Tail of exactly 8 bytes (guid_marker + pin_count) returns empty pins list."""
        tail = u32(0) + i32(0)  # guid_marker=0, pin_count=0
        archive = ByteArchive(tail, tolerant=True)
        name_map: list[str] = []

        result = _decode_pins_from_tail(archive, name_map, tail_offset=0, tail_size=len(tail))

        assert result == []


class TestExistingSampleRegression:
    """Regression: existing Niagara sample still parses."""

    @pytest.mark.samples
    def test_nm_bp_system_event_parses(self):
        """NM_BPSystemEvent.uasset parses without error."""
        sample_path = Path(__file__).resolve().parents[1] / "samples" / "NM_BPSystemEvent.uasset"
        if not sample_path.exists():
            pytest.skip("Sample not available")

        result = parse_uasset_with_linker(str(sample_path), tolerant=True)
        assert result.is_success, f"Parse failed: {result.errors}"
        assert result.linker is not None
        assert result.export_map is not None
